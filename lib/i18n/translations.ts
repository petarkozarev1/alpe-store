export function hasEnglishTranslation(source: string) {
  return Object.prototype.hasOwnProperty.call(englishTranslations, source)
}

export function translate(locale: Locale, source: string) {
  return locale === 'en' ? englishTranslations[source] ?? source : source
}

export function localizeValue<T>(locale: Locale, value: T): T {
  if (typeof value === 'string') return translate(locale, value) as T
  if (Array.isArray(value)) return value.map(item => localizeValue(locale, item)) as T
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localizeValue(locale, item)])) as T
  }
  return value
}
